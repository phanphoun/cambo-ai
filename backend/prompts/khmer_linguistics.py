def sanitize_unwanted_thai(text: str, user_prompt: str = "") -> str:
    """Sanitizes accidental Thai script or polite formulas that LLMs may inadvertently

    mix into Khmer responses, unless the user explicitly requested Thai language.
    """
    if not text:
        return text

    # If the user explicitly requested Thai, preserve Thai output
    lower_prompt = user_prompt.lower()
    if any(k in lower_prompt for k in ["thai", "ថៃ", "ภาษาไทย", "to thai", "in thai", "ជាភាសាថៃ", "ភាសាថៃ"]):
        return text

